def _criteria_block() -> str:
    lines = []
    for c in Criterion:
        lines.append(f"- {c.value} ({NAME_RU[c]}): {DEFINITION_RU[c]}")
    return "\n".join(lines)


def _roles_block() -> str:
    return "\n".join(f"- {r.value} — {_ROLE_RU[r]}" for r in Role)


